"""Writes menu_cjk_font.h: the few CJK glyphs the in-game menu shows (the native names of the game's Japanese, Korean
and Chinese languages, menu.cpp kGameLanguages), cut from Noto Sans CJK JP Regular (SIL Open Font License 1.1) and
converted to TrueType outlines (ImGui's stb_truetype reads no CFF). The menu merges them into its system font, so they
show on any system, with or without CJK fonts. Run again only when kGameLanguages gets other CJK characters:

    python astral_chain/runtime/las/make_menu_cjk_font.py /usr/share/fonts/noto-cjk/NotoSansCJK-Regular.ttc

(needs fontTools)."""
import io
import sys
from pathlib import Path

from fontTools import subset
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.ttLib import TTFont, newTable

TEXT = '日本語한국어繁體中文简体中文'
OUT = Path(__file__).with_name('menu_cjk_font.h')


def main(source):
    font = TTFont(source, fontNumber=0)   # (Noto Sans CJK JP in the collection)
    if font['name'].getDebugName(1) != 'Noto Sans CJK JP':
        raise SystemExit(f'expected Noto Sans CJK JP first in {source}, found {font["name"].getDebugName(1)}')
    options = subset.Options()
    options.layout_features = []
    options.hinting = False
    options.name_IDs = ['*']
    options.notdef_outline = True
    sub = subset.Subsetter(options)
    sub.populate(text=TEXT)
    sub.subset(font)
    # CFF -> glyf (fontTools' otf2ttf recipe): quadratic outlines, maximum error 1 unit
    order = font.getGlyphOrder()
    glyphs = font.getGlyphSet()
    out = {}
    for name in order:
        pen = TTGlyphPen(glyphs)
        glyphs[name].draw(Cu2QuPen(pen, 1.0, reverse_direction=True))
        out[name] = pen.glyph()
    del font['CFF ']
    if 'VORG' in font:
        del font['VORG']
    font['glyf'] = newTable('glyf')
    font['glyf'].glyphOrder = order
    font['glyf'].glyphs = out
    font['loca'] = newTable('loca')
    font['maxp'].tableVersion = 0x00010000
    for attr in ('maxZones', 'maxTwilightPoints', 'maxStorage', 'maxFunctionDefs', 'maxInstructionDefs',
                 'maxStackElements', 'maxSizeOfInstructions', 'maxComponentElements'):
        setattr(font['maxp'], attr, 0)
    font['maxp'].maxZones = 1
    font['head'].indexToLocFormat = 0
    font['head'].glyphDataFormat = 0
    font['post'].formatType = 2.0
    font['post'].extraNames = []
    font['post'].mapping = {}
    font.sfntVersion = '\x00\x01\x00\x00'
    data = io.BytesIO()
    font.save(data)
    data = data.getvalue()
    lines = [f'// Generated by make_menu_cjk_font.py from Noto Sans CJK JP Regular (SIL Open Font License 1.1,',
             f'// Copyright 2014-2021 Adobe; THIRD_PARTY_NOTICES.md): the glyphs of "{TEXT}". Do not edit.',
             '#pragma once', f'static const unsigned char kMenuCjkFont[{len(data)}] = {{']
    for i in range(0, len(data), 24):
        lines.append('    ' + ','.join(str(b) for b in data[i:i + 24]) + ',')
    lines += ['};', f'static const char kMenuCjkText[] = "{TEXT}";', '']
    OUT.write_text('\n'.join(lines), encoding='utf-8')
    print(f'{OUT}: {len(data)} bytes, {len(order)} glyphs')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/noto-cjk/NotoSansCJK-Regular.ttc')
